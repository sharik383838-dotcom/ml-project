"""
Stock Price Prediction Service.
Coordinates data retrieval, feature engineering, model training, evaluation,
and persistence of prediction records.
"""

import logging
from datetime import datetime, timedelta
import pandas as pd
from backend.services import yahoo_service
from backend.services.cache_service import cache_get, cache_set
from backend.models.features import build_prediction_features
from backend.models.predictor import train_and_evaluate_model
from backend.database import save_prediction_record

logger = logging.getLogger(__name__)


def _estimate_next_trading_day(last_date_str):
    """Estimate the next market trading date (skip weekends)."""
    try:
        last_dt = datetime.fromisoformat(last_date_str.split('T')[0].split(' ')[0])
        next_dt = last_dt + timedelta(days=1)
        # Skip Saturday (5) and Sunday (6)
        while next_dt.weekday() >= 5:
            next_dt += timedelta(days=1)
        return next_dt.strftime('%Y-%m-%d')
    except Exception:
        # Fallback to tomorrow + weekend skip
        now = datetime.now()
        nxt = now + timedelta(days=1)
        while nxt.weekday() >= 5:
            nxt += timedelta(days=1)
        return nxt.strftime('%Y-%m-%d')


def generate_stock_prediction(ticker_symbol, user_id=None, force_refresh=False):
    """
    Generate ML-based stock price prediction for a given ticker symbol.

    Args:
        ticker_symbol: Uppercase stock ticker (e.g. AAPL, MSFT, RELIANCE.NS)
        user_id: Optional ID of the authenticated user requesting the prediction
        force_refresh: Whether to bypass cache

    Returns:
        dict: Complete prediction result with metrics, chart series, and metadata.
    """
    ticker_symbol = ticker_symbol.upper()
    cache_key = f'prediction_{ticker_symbol}'

    if not force_refresh:
        cached = cache_get(cache_key, ttl=600)  # 10 min cache
        if cached is not None:
            return cached

    # 1. Fetch real historical OHLCV market data (2 years of daily data for robust training)
    history = yahoo_service.get_history(ticker_symbol, period='2y', interval='1d')
    if not history or len(history) < 60:
        # Try 1y fallback if 2y is unavailable for newer listings
        history = yahoo_service.get_history(ticker_symbol, period='1y', interval='1d')

    if not history or len(history) < 50:
        raise ValueError(f"Insufficient historical market data for {ticker_symbol} to train ML model. Need at least 50 trading days.")

    # Convert to DataFrame
    df = pd.DataFrame(history)
    df['date'] = pd.to_datetime(df['date'], utc=True)
    df = df.sort_values('date').reset_index(drop=True)

    # 2. Build Technical, Volatility, and Volume Features
    clean_df, feature_cols, target_col, latest_row, full_feature_df = build_prediction_features(df)

    # 3. Train and evaluate model with chronological split
    results = train_and_evaluate_model(
        clean_df=clean_df,
        feature_cols=feature_cols,
        target_col=target_col,
        latest_row=latest_row,
        test_size=0.2,
        model_type='rf'
    )

    last_record_date = df['date'].iloc[-1].strftime('%Y-%m-%d')
    next_period_date = _estimate_next_trading_day(last_record_date)

    # 4. Assemble clean result package
    prediction_result = {
        'symbol': ticker_symbol,
        'modelName': results['modelName'],
        'currentPrice': results['currentPrice'],
        'predictedPrice': results['predictedPrice'],
        'predictedChange': results['predictedChange'],
        'predictedChangePercent': results['predictedChangePercent'],
        'direction': results['direction'],
        'uncertaintyInterval': results['uncertaintyInterval'],
        'predictionDate': next_period_date,
        'lastTradingDate': last_record_date,
        'metrics': results['metrics'],
        'chartComparison': {
            'dates': results['chartComparison']['dates'],
            'actualPrices': results['chartComparison']['actualPrices'],
            'predictedPrices': results['chartComparison']['predictedPrices'],
            'forecastDate': next_period_date,
            'forecastPrice': results['predictedPrice']
        },
        'featureImportances': results['featureImportances'],
        'sampleCounts': {
            'totalSamples': len(df),
            'trainSamples': results['trainSamples'],
            'testSamples': results['testSamples'],
            'featuresUsed': len(feature_cols)
        },
        'disclaimer': (
            'Stock price predictions are statistical estimates generated by machine learning '
            'models trained on historical technical indicators. Financial markets are inherently '
            'volatile and subject to unforeseen real-world events. This analysis does not guarantee '
            'future performance and does not constitute financial, investment, or trading advice.'
        ),
        'marketDataTimestamp': last_record_date,
        'isRealTime': False
    }

    # 5. Persist to database prediction history
    try:
        save_prediction_record(
            ticker=ticker_symbol,
            current_price=results['currentPrice'],
            predicted_price=results['predictedPrice'],
            predicted_change=results['predictedChange'],
            predicted_change_pct=results['predictedChangePercent'],
            mae=results['metrics']['mae'],
            rmse=results['metrics']['rmse'],
            directional_accuracy=results['metrics']['directionalAccuracy'],
            model_name=results['modelName'],
            user_id=user_id
        )
    except Exception as e:
        logger.warning(f'Could not persist prediction history: {e}')

    # Cache result
    cache_set(cache_key, prediction_result, ttl=600)
    return prediction_result
